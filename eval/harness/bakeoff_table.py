"""Build the OCR bake-off tables in docs/blueprint/14-run-profiles.md from the extraction reports.

    PYTHONPATH=eval uv run python -m harness.bakeoff_table            # print the generated block
    PYTHONPATH=eval uv run python -m harness.bakeoff_table --write    # replace it in the document

Every number comes from var/eval/extraction-golden-<label>.json (written by
``make eval-extraction OCR=... LABEL=...``), except the Docker run's, which is read from the
scratch directory that run wrote (``DOCKER_REPORT``). The document holds the block between two
marker comments and nothing in it is typed by hand.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from fra_ingest.config import REPO_ROOT
from harness.extraction import OUT as EVAL
from harness.extraction import SCANNED as GATE
from harness.extraction import wilson_interval

# var may be a link to another checkout's var, so reports are found through it, not copied.
DOCKER_REPORT = (
    REPO_ROOT
    / "var"
    / "docker-bakeoff"
    / "run1"
    / "eval"
    / "extraction-golden-docker-tesseract.json"
)
DOCUMENT = REPO_ROOT / "docs" / "blueprint" / "14-run-profiles.md"
BEGIN = "<!-- bakeoff:begin (generated by harness.bakeoff_table) -->"
END = "<!-- bakeoff:end -->"

# Display name and report path, in the order of the table.
RUNS: Sequence[tuple[str, Path]] = (
    ("Vision (ocrmac), accurate", EVAL / "extraction-golden-ocrmac.json"),
    ("Tesseract `ara`, psm 3", EVAL / "extraction-golden-tesseract.json"),
    ("Tesseract `ara`, psm 6", EVAL / "extraction-golden-tesseract-psm6.json"),
    ("Tesseract `ara`, psm 3, ocr_scale 4.0", EVAL / "extraction-golden-tesseract-scale4.json"),
    ("Tesseract `ara+eng`, psm 3", EVAL / "extraction-golden-tesseract-ara-eng.json"),
    (
        "Tesseract `ara+eng`, psm 3, 300 dpi page reads",
        EVAL / "extraction-golden-tesseract-ara-eng-dpi300.json",
    ),
    ("Tesseract `ara+eng`, psm 3, in Docker", DOCKER_REPORT),
)


def load(path: Path) -> dict[str, Any]:
    if not path.is_file():
        msg = f"missing report {path}: run the bake-off for it first"
        raise FileNotFoundError(msg)
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def report_line(report: Mapping[str, Any], prefix: str) -> str:
    for line in report["report"]:
        if line.startswith(prefix):
            return str(line)
    msg = f"report {report['label']} has no line starting {prefix!r}"
    raise ValueError(msg)


def platform_name(report: Mapping[str, Any]) -> str:
    """The platform string the run recorded about itself."""
    return f"`{report_line(report, 'platform: ').removeprefix('platform: ')}`"


def checked_scanned(report: Mapping[str, Any]) -> list[dict[str, Any]]:
    rows = [r for r in report["scanned"] if r["status"] == "checked"]
    if {r["language"] for r in rows} != {"ar", "en"}:
        msg = f"report {report['label']}: expected checked scanned rows for ar and en"
        raise ValueError(msg)
    return sorted(rows, key=lambda r: r["language"])


def pct(value: float, places: int = 1) -> str:
    return f"{100 * value:.{places}f}%"


def seconds(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.2f}"


def table(reports: Sequence[tuple[str, dict[str, Any]]]) -> list[str]:
    lines = [
        "| Engine and setting | Language | Right of n | Accuracy | 95% interval | Value only "
        "| Statements extracted | s per OCR call | Convert s per page | Platform |",
        "|---|:-:|--:|--:|:-:|--:|:-:|--:|--:|---|",
    ]
    for name, report in reports:
        for row in checked_scanned(report):
            lines.append(
                f"| {name} | {row['language']} | {row['right']} of {row['cells']} "
                f"| {pct(row['accuracy'])} "
                f"| {pct(row['wilson_low'])} to {pct(row['wilson_high'])} "
                f"| {pct(row['value_only_accuracy'])} "
                f"| {row['statements_found']} of {row['statements']} "
                f"| {seconds(row['read_seconds_per_call'])} "
                f"| {seconds(row['convert_seconds_per_page'])} "
                f"| {platform_name(report)} |"
            )
    return lines


def tesseract_records(reports: Sequence[tuple[str, dict[str, Any]]]) -> list[str]:
    """The version and data hashes of each Tesseract run, one line per distinct record."""
    seen: dict[str, list[str]] = {}
    for name, report in reports:
        if report["engine"] != "tesseract":
            continue
        version = report_line(report, "tesseract: ").removeprefix("tesseract: ")
        hashes = [
            line.strip().replace(" sha256 ", " sha256 `") + "`"
            for line in report["report"]
            if "traineddata sha256" in line
        ]
        key = f"{platform_name(report)}: {version}; " + "; ".join(hashes)
        seen.setdefault(key, []).append(name)
    return [f"- {key}" for key in seen]


def settings_lines(reports: Sequence[tuple[str, dict[str, Any]]]) -> list[str]:
    out = []
    for name, report in reports:
        if report["engine"] == "tesseract":
            text = report_line(report, "tesseract settings: ").removeprefix("tesseract settings: ")
            out.append(f"- {name}: {text}")
    return out


def reading_lines(reports: Sequence[tuple[str, dict[str, Any]]]) -> list[str]:
    arabic = [(n, checked_scanned(r)[0]) for n, r in reports]
    best_name, best = max(arabic, key=lambda item: item[1]["right"])
    cells = best["cells"]
    needed = math.ceil(GATE * cells)
    perfect_low = wilson_interval(cells, cells)[0]
    widest = max(
        (row["wilson_high"] - row["wilson_low"]) / 2
        for _, report in reports
        for row in checked_scanned(report)
        if row["right"] > 0
    )
    top_high = max(row["wilson_high"] for _, row in arabic)
    below = [n for n, row in arabic if row["right"] / row["cells"] < GATE]
    return [
        f"- Best scanned-Arabic score: {best['right']} of {cells} ({pct(best['accuracy'])}), "
        f"{best_name}. The gate ({pct(GATE)}) needs {needed} of {cells}. "
        f"{len(below)} of {len(arabic)} runs are below it.",
        f"- A perfect score on {cells} cells has a 95% lower bound of {pct(perfect_low)}, so "
        f"{pct(GATE)} cannot be shown at this n. The highest upper bound among the Arabic runs "
        f"is {pct(top_high)}; that rules {pct(GATE)} out for this one document, not for Arabic "
        "scans in general.",
        f"- Among runs with a nonzero score, the widest 95% interval is plus or minus "
        f"{100 * widest:.1f} points: runs closer than that cannot be told apart.",
    ]


def generate(runs: Sequence[tuple[str, Path]] = RUNS) -> str:
    reports = [(name, load(path)) for name, path in runs]
    parts = [
        *table(reports),
        "",
        "Tesseract runs, version and data:",
        "",
        *tesseract_records(reports),
        "",
        "Tesseract settings per run (page-read resolution `ocr_dpi`, docling's `ocr_scale`):",
        "",
        *settings_lines(reports),
        "",
        "Read from the table:",
        "",
        *reading_lines(reports),
    ]
    return "\n".join(parts)


def replace_block(text: str, block: str) -> str:
    """``text`` with the block between the markers replaced; no markers is an error."""
    start, stop = text.find(BEGIN), text.find(END)
    if start < 0 or stop < start:
        msg = f"the document has no {BEGIN!r} ... {END!r} block"
        raise ValueError(msg)
    return text[: start + len(BEGIN)] + "\n\n" + block + "\n\n" + text[stop:]


def main(
    argv: Sequence[str] | None = None,
    *,
    runs: Sequence[tuple[str, Path]] = RUNS,
    document: Path = DOCUMENT,
) -> int:
    parser = argparse.ArgumentParser(prog="python -m harness.bakeoff_table")
    parser.add_argument("--write", action="store_true", help=f"replace the block in {document}")
    args = parser.parse_args(argv)
    block = generate(runs)
    # Without --write the markers are still required: the block has a place to go.
    updated = replace_block(document.read_text(encoding="utf-8"), block)
    if args.write:
        document.write_text(updated, encoding="utf-8")
    else:
        print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
